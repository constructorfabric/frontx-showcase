/**
 * What `generate` writes from the brand record: `src/tokens.css`, `src/theme.ts` and the token table of the AI guideline.
 */
import type { Brand, BrandRow, HeadRow, Kit } from './model.ts';

/** The light selector: the document in any appearance but dark, and every light scope, with two attribute conditions so it outranks the kit's single-attribute `[data-theme='light']` block on a themed frame whatever the order of the two sheets. */
export const LIGHT_SELECTOR = ":root:not([data-theme='dark']),\n[data-theme='light']:not([data-theme='dark'])";
export const DARK_SELECTOR = "[data-theme='dark']";
export const GUIDELINE_START = '<!-- brand:tokens:start (generated by brand:generate from src/brand.json; do not edit) -->';
export const GUIDELINE_END = '<!-- brand:tokens:end -->';

const declare = (rows: readonly BrandRow[]) =>
  rows
    .filter((row) => row.value !== null)
    .map((row) => `  /* ${row.role.replace(/\*\//g, '* /')} */\n  ${row.token}: ${row.value};`)
    .join('\n');

// @cpt-algo:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1
/** The token stylesheet: light values (kit overrides, then brand tokens), dark resets, theme-invariant tokens. */
export function renderTokensCss(brand: Brand): string {
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-header
  const header = [
    '/*',
    ' * Generated by `brand:generate` from src/brand.json; do not edit. Change brand.json and generate again: `brand:check` fails on any difference.',
    ' *',
    ' * Light: the brand values on kit tokens and the brand tokens the kit lacks, under a selector that outranks the kit light block on every light scope. Dark: the kit keeps its own dark palette; only the brand tokens are reset, on every dark scope. Theme-invariant: the display type, weights, tracking, radii and motifs.',
    ' */',
  ].join('\n');
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-header
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-light
  const light = `${LIGHT_SELECTOR} {\n${declare([...brand.light.overrides, ...brand.light.tokens])}\n}`;
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-light
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-dark
  const dark = `${DARK_SELECTOR} {\n${declare(brand.dark.tokens)}\n}`;
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-dark
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-invariant
  const invariant = `:root {\n${declare(brand.invariant)}\n}`;
  return `${header}\n\n${light}\n\n${dark}\n\n${invariant}\n`;
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-tokens:p1:inst-tokens-invariant
}

const entries = (palette: Readonly<Record<string, string>>) =>
  Object.entries(palette)
    .map(([name, value]) => `  '${name}': '${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`)
    .join('\n');

// @cpt-algo:cpt-template-site-brand-algo-brand-source-and-generation-render-theme:p1
/** The theme variables: the kit's complete light palette with the brand overrides applied, and the kit's dark palette, for the theme registry. */
export function renderThemeTs(brand: Brand, kit: Kit): string {
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-theme:p1:inst-merge-light
  const light: Record<string, string> = { ...kit.light };
  for (const row of brand.light.overrides) if (row.value !== null) light[row.token] = row.value;
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-theme:p1:inst-merge-light
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-theme:p1:inst-render-module
  return [
    '// Generated by `brand:generate` from src/brand.json and the installed @gears-frontx/ui-kit theme.css; do not edit.',
    '// The complete variable sets of the two appearances, shaped as theme-registry variables: the kit light palette with the brand overrides, and the kit dark palette. The site delivers the brand through document.css today; these sets are what a theme registry that reaches every scope takes instead.',
    '',
    'export const brandLightVariables: Readonly<Record<string, string>> = {',
    entries(light),
    '};',
    '',
    'export const brandDarkVariables: Readonly<Record<string, string>> = {',
    entries(kit.dark),
    '};',
    '',
    'export const brandThemes = {',
    "  light: { appearance: 'light', variables: brandLightVariables },",
    "  dark: { appearance: 'dark', variables: brandDarkVariables },",
    '} as const;',
    '',
  ].join('\n');
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-theme:p1:inst-render-module
}

const cell = (value: string | null | undefined) => (value === null || value === undefined ? 'none' : `\`${value.replace(/\|/g, '\\|')}\``);
const note = (row: { reason?: string; role: string }) => [row.role, row.reason].filter(Boolean).join('. ').replace(/\|/g, '\\|');

// @cpt-algo:cpt-template-site-brand-algo-brand-source-and-generation-render-table:p2
/** The guideline's token table: every row with our value, the V2 value, the role and the reason for a difference. */
export function renderTokenTable(brand: Brand): string {
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-table:p2:inst-table-rows
  const section = (title: string, rows: readonly BrandRow[]) => [
    '',
    `**${title}**`,
    '',
    '| Token | Ours | V2 | Role and reason |',
    '| --- | --- | --- | --- |',
    ...rows.map((row) => `| \`${row.token}\` | ${row.value === null ? 'not adopted' : cell(row.value)} | ${cell(row.v2)} | ${note(row)} |`),
  ];
  const head = (name: string, row: HeadRow) => `| \`${name}\` | ${cell(row.value)} | ${cell(row.v2)} | ${note(row)} |`;
  return [
    ...section('Light: kit tokens the brand overrides', brand.light.overrides),
    ...section('Light: brand tokens', brand.light.tokens),
    ...section('Dark: brand token resets', brand.dark.tokens),
    ...section('Theme-invariant brand tokens', brand.invariant),
    '',
    '**Head colours (site config)**',
    '',
    '| Key | Ours | V2 | Role and reason |',
    '| --- | --- | --- | --- |',
    head('themeColor', brand.head.themeColor),
    head('backgroundColor', brand.head.backgroundColor),
    '',
  ].join('\n');
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-table:p2:inst-table-rows
}

/** The guideline with the text between its two table markers replaced by `table`. */
export function spliceTable(guideline: string, table: string): string {
  // @cpt-begin:cpt-template-site-brand-algo-brand-source-and-generation-render-table:p2:inst-table-splice
  const start = guideline.indexOf(GUIDELINE_START);
  const end = guideline.indexOf(GUIDELINE_END);
  if (start === -1 || end === -1 || end < start) throw new Error('the guideline lacks the brand:tokens markers');
  return `${guideline.slice(0, start + GUIDELINE_START.length)}\n${table}\n${guideline.slice(end)}`;
  // @cpt-end:cpt-template-site-brand-algo-brand-source-and-generation-render-table:p2:inst-table-splice
}
