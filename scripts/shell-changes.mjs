/** The text adaptation every applied text file carries, the one rule of the repository's text policy that template text can break: the same long-dash rule the catalogue generator applies. A file that differs from the pristine one by this rule only is adapted, not changed: it is neither recorded nor site-owned. */
export const ADAPTATIONS = [{ id: 'long-dash', description: 'long dashes become "-"', pattern: /[\u2013\u2014]/g, replace: '-' }];

/** Whether a file's content is binary (a NUL byte in its first 8 KiB, as in `policy-text.mjs`). @param {Buffer} buffer */
function isBinary(buffer) {
  return buffer.subarray(0, 8192).includes(0);
}

// @cpt-algo:cpt-site-algo-shell-change-ledger-adapt:p2
/**
 * A pristine file's bytes with the adaptations applied; a binary file is returned as it is.
 * @param {Buffer} buffer
 * @returns {Buffer}
 */
export function adapt(buffer) {
  // @cpt-begin:cpt-site-algo-shell-change-ledger-adapt:p2:inst-adapt-binary
  if (isBinary(buffer)) return buffer;
  // @cpt-end:cpt-site-algo-shell-change-ledger-adapt:p2:inst-adapt-binary
  // @cpt-begin:cpt-site-algo-shell-change-ledger-adapt:p2:inst-adapt-text
  let text = buffer.toString('utf8');
  for (const rule of ADAPTATIONS) text = text.replace(rule.pattern, rule.replace);
  return Buffer.from(text, 'utf8');
  // @cpt-end:cpt-site-algo-shell-change-ledger-adapt:p2:inst-adapt-text
}

// @cpt-algo:cpt-site-algo-shell-change-ledger-owned-files:p2
