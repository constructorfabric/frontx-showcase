/** The site-owned applied files, relative to the repository root: the changed and added files of every applied template's ledger. */
export function ownedAppliedFiles() {
  // @cpt-begin:cpt-site-algo-shell-change-ledger-owned-files:p2:inst-owned
  return APPLIED_TEMPLATES.flatMap(({ changes }) => [...changes.changed, ...changes.added]).map((file) => `site/${file}`);
  // @cpt-end:cpt-site-algo-shell-change-ledger-owned-files:p2:inst-owned
}

/** Directories the comparison never walks when git cannot list the files, and the files the build or the composition step writes. */
const SKIP_DIRS = new Set(['node_modules', 'dist', 'dist-lib', 'coverage']);
const GENERATED = new Set(['public/generated-mfe-manifests.json', 'src-app/app/mfe/generated-mfe-manifests.json']);

/**
 * Every file of a directory but the skipped directories: the pristine template in the CLI inventory, which sits in the repository's ignored `.frontx-inventory/` and so cannot be listed through git.
 * @param {string} dir
 * @returns {string[]}
 */
function walkedFiles(dir) {
  const files = [];
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (SKIP_DIRS.has(entry.name)) continue;
      const child = path.join(current, entry.name);
      if (entry.isDirectory()) walk(child);
      else files.push(path.relative(dir, child).split(path.sep).join('/'));
    }
  };
  walk(dir);
  return files;
}

/**
 * The files of the site's directory that git would record (`git ls-files --cached --others --exclude-standard`, like `policy-text.mjs`), relative to it. Git applies `.gitignore`, so editor droppings, build info and caches are never part of the comparison. Outside a git checkout every file but the skipped directories counts.
 * @param {string} dir
 * @returns {string[]}
 */
function recordedFiles(dir) {
  try {
    const out = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 });
    // An index entry can outlive its file; a file that is not on disk is not part of the tree.
    return [...new Set(out.split('\0').filter(Boolean))].filter((file) => fs.existsSync(path.join(dir, file)));
  } catch {
    return walkedFiles(dir);
  }
}

/** The files of `all` that lie in a subtree: the subtree itself when it is a file, or everything below it. */
function filesUnder(all, subtree) {
  return all.filter((file) => file === subtree || file.startsWith(`${subtree}/`)).filter((file) => !file.split('/').some((part) => SKIP_DIRS.has(part)));
}

// @cpt-algo:cpt-site-algo-shell-change-ledger-diff:p2
// @cpt-dod:cpt-site-dod-shell-change-ledger-exact-list:p2
/**
 * The actual changes of `site/` against a pristine applied template directory, over the subtrees the template's manifest claims.
 * @param siteDir - `site/`
 * @param templateDir - the template's directory in the CLI inventory
 * @returns {{ changed: string[], added: string[], removed: string[], adapted: string[], unadapted: string[] }} adapted: differ from the pristine file by the adaptations only; unadapted: kept byte for byte although the adaptations change them
 */
export function diffShell(siteDir, templateDir) {
  // @cpt-begin:cpt-site-algo-shell-change-ledger-diff:p2:inst-claimed
  const manifest = JSON.parse(fs.readFileSync(path.join(templateDir, 'frontx-template.json'), 'utf8'));
  const claimed = manifest.ownershipBoundaries.exclusiveSubtrees.map((subtree) => subtree.replace(/\/$/, ''));
  // @cpt-end:cpt-site-algo-shell-change-ledger-diff:p2:inst-claimed
  // @cpt-begin:cpt-site-algo-shell-change-ledger-diff:p2:inst-pristine-files
  const pristineFiles = walkedFiles(templateDir);
  // @cpt-end:cpt-site-algo-shell-change-ledger-diff:p2:inst-pristine-files
  // @cpt-begin:cpt-site-algo-shell-change-ledger-diff:p2:inst-current-files
  const currentFiles = recordedFiles(siteDir);
  // @cpt-end:cpt-site-algo-shell-change-ledger-diff:p2:inst-current-files
  // @cpt-begin:cpt-site-algo-shell-change-ledger-diff:p2:inst-restrict
  const pristine = new Set(claimed.flatMap((subtree) => filesUnder(pristineFiles, subtree)).filter((file) => !GENERATED.has(file)));
  const current = new Set(claimed.flatMap((subtree) => filesUnder(currentFiles, subtree)).filter((file) => !GENERATED.has(file)));
  // @cpt-end:cpt-site-algo-shell-change-ledger-diff:p2:inst-restrict
  // @cpt-begin:cpt-site-algo-shell-change-ledger-diff:p2:inst-changed
  const changed = [];
  const adapted = [];
  const unadapted = [];
  for (const file of [...pristine].filter((name) => current.has(name))) {
    const original = fs.readFileSync(path.join(templateDir, file));
    const site = fs.readFileSync(path.join(siteDir, file));
    const expected = adapt(original);
    if (site.equals(original)) {
      if (!expected.equals(original)) unadapted.push(file);
    } else if (site.equals(expected)) adapted.push(file);
    else changed.push(file);
  }
  // @cpt-end:cpt-site-algo-shell-change-ledger-diff:p2:inst-changed
  // @cpt-begin:cpt-site-algo-shell-change-ledger-diff:p2:inst-return-diff
  return {
    changed: changed.sort(),
    added: [...current].filter((file) => !pristine.has(file)).sort(),
    removed: [...pristine].filter((file) => !current.has(file)).sort(),
    adapted: adapted.sort(),
    unadapted: unadapted.sort(),
  };
  // @cpt-end:cpt-site-algo-shell-change-ledger-diff:p2:inst-return-diff
}

/** Whether a recorded entry covers a file: the same path, or a folder entry (ending in `/`) the file lies under. */
function covers(entry, file) {
  return entry.endsWith('/') ? file.startsWith(entry) : entry === file;
}

// @cpt-algo:cpt-site-algo-shell-change-ledger-compare:p2
/**
 * Differences between a template's recorded list and the actual changes, as messages.
 * @param actual - what `diffShell` found
 * @param recorded - the template's ledger
 * @param template - the template's name and the ledger's name, for the messages
 */
export function compareChanges(actual, recorded = SHELL_CHANGES, template = { name: 'template-shell', ledger: 'SHELL_CHANGES' }) {
  // @cpt-begin:cpt-site-algo-shell-change-ledger-compare:p2:inst-compare-kinds
  const errors = [];
  for (const kind of ['changed', 'added', 'removed']) {
    const want = recorded[kind];
    const have = actual[kind];
    for (const file of have) if (!want.some((entry) => covers(entry, file))) errors.push(`site/${file} is ${kind} against ${template.name} and not recorded in ${template.ledger}.${kind}`);
    for (const entry of want) if (!have.some((file) => covers(entry, file))) errors.push(`${template.ledger}.${kind} records site/${entry}, which is not ${kind} against ${template.name}`);
  }
  // @cpt-end:cpt-site-algo-shell-change-ledger-compare:p2:inst-compare-kinds
  // @cpt-begin:cpt-site-algo-shell-change-ledger-compare:p2:inst-compare-unadapted
  for (const file of actual.unadapted ?? []) errors.push(`site/${file} keeps text of ${template.name} the adaptations change (${ADAPTATIONS.map((rule) => rule.description).join('; ')}); run npm run shell:changes -- --adapt`);
  // @cpt-end:cpt-site-algo-shell-change-ledger-compare:p2:inst-compare-unadapted
  // @cpt-begin:cpt-site-algo-shell-change-ledger-compare:p2:inst-return-messages
  return errors;
  // @cpt-end:cpt-site-algo-shell-change-ledger-compare:p2:inst-return-messages
}

// @cpt-flow:cpt-site-flow-shell-change-ledger-run:p2
if (isEntryPoint(import.meta.url)) {
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-run
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const siteDir = path.join(root, 'site');
  const templateDir = (/** @type {{ identity: string }} */ template) => path.join(root, '.frontx-inventory', ...template.identity.split('/'));
  const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--adapt') ? 'adapt' : 'print';
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-run
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-print
  if (mode === 'print') {
    for (const template of APPLIED_TEMPLATES) for (const kind of ['changed', 'added', 'removed']) for (const file of template.changes[kind]) console.log(`${template.name}\t${kind}\tsite/${file}`);
    process.exit(0);
  }
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-print
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-inventory-missing
  const missing = APPLIED_TEMPLATES.filter((template) => !fs.existsSync(path.join(templateDir(template), 'frontx-template.json')));
  if (missing.length > 0) {
    console.error(`shell:changes: ${missing.map((template) => template.name).join(', ')} not in .frontx-inventory; run npm run site:data first, which installs the applied templates`);
    process.exit(1);
  }
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-inventory-missing
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-adapt
  if (mode === 'adapt') {
    let written = 0;
    for (const template of APPLIED_TEMPLATES) {
      for (const file of diffShell(siteDir, templateDir(template)).unadapted) {
        fs.writeFileSync(path.join(siteDir, file), adapt(fs.readFileSync(path.join(templateDir(template), file))));
        written += 1;
      }
    }
    console.log(`shell:changes: adapted ${written} applied files`);
    process.exit(0);
  }
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-adapt
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-compare
  const errors = APPLIED_TEMPLATES.flatMap((template) => compareChanges(diffShell(siteDir, templateDir(template)), template.changes, template));
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-compare
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-fail
  if (errors.length > 0) {
    for (const error of errors) console.error(`shell:changes: ${error}`);
    process.exit(1);
  }
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-fail
  // @cpt-begin:cpt-site-flow-shell-change-ledger-run:p2:inst-pass
  console.log(`shell:changes: the recorded changes and the adaptations match site/ against ${APPLIED_TEMPLATES.map((template) => template.name).join(', ')}`);
  // @cpt-end:cpt-site-flow-shell-change-ledger-run:p2:inst-pass
}
